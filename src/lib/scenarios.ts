import { type Scenario, type TreeNode, type DecisionTree } from "./domain";

type Route = {
  title: string;
  pros: string[];
  risks: string[];
  question: string;
  paths: { title: string; steps: [string, string][] }[];
};
function tree(title: string, routes: Route[]): DecisionTree {
  const nodes: TreeNode[] = [
    {
      id: "root",
      title,
      pros: [],
      risks: [],
      children: routes.map((_, i) => `route-${i}`),
      steps: [],
    },
  ];
  routes.forEach((route, i) => {
    nodes.push({
      id: `route-${i}`,
      title: route.title,
      question: route.question,
      pros: route.pros,
      risks: route.risks,
      children: route.paths.map((_, j) => `leaf-${i}-${j}`),
      steps: [],
    });
    route.paths.forEach((path, j) =>
      nodes.push({
        id: `leaf-${i}-${j}`,
        title: path.title,
        pros: [],
        risks: [],
        children: [],
        steps: path.steps.map(([title, hint], k) => ({
          id: `step-${i}-${j}-${k}`,
          title,
          hint,
        })),
      }),
    );
  });
  return { rootId: "root", nodes };
}
