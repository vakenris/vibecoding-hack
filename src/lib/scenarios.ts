import { type Scenario, type TreeNode, type DecisionTree } from "./domain";

type Option = { id: string; title: string; pros: string[]; risks: string[] };
type Selection = Record<string, string>;
type Decision = {
  id: string;
  question: string;
  options: (selected: Selection) => Option[];
};
type Step = [title: string, hint: string];
const option = (
  id: string,
  title: string,
  pro: string,
  risk: string,
): Option => ({ id, title, pros: [pro], risks: [risk] });

// Expand each context-dependent decision into its own nodes. Every terminal plan
// includes the exact selections along its path; ids are stable within version 2.
function detailedTree(
  title: string,
  decisions: Decision[],
  checklist: (selected: Selection) => Step[],
): DecisionTree {
  const nodes: TreeNode[] = [];
  function append(
    id: string,
    title: string,
    depth: number,
    selected: Selection,
    pros: string[] = [],
    risks: string[] = [],
  ) {
    const decision = decisions[depth];
    const node: TreeNode = { id, title, pros, risks, children: [], steps: [] };
    nodes.push(node);
    if (!decision) {
      node.steps = checklist(selected).map(([title, hint], index) => ({
        id: `${id}-step-${index}`,
        title,
        hint,
      }));
      return;
    }
    node.question = decision.question;
    for (const choice of decision.options(selected)) {
      const childId = `${id}-${choice.id}`;
      node.children.push(childId);
      append(
        childId,
        choice.title,
        depth + 1,
        { ...selected, [decision.id]: choice.id },
        choice.pros,
        choice.risks,
      );
    }
  }
  append("root", title, 0, {});
  return { rootId: "root", nodes };
}
